// One delegated pointer controller for all cards. Stable layout bounds avoid
// feedback from the card's own transform; animation frames coalesce movement.
const memberTiltPointer = window.matchMedia("(any-hover: hover) and (any-pointer: fine)");
const memberReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
let tiltedMember = null;
let memberTiltFrame = 0;
let memberTiltBounds = null;
let memberPointer = { x: 0, y: 0 };

function resetMemberTilt() {
  cancelAnimationFrame(memberTiltFrame);
  memberTiltFrame = 0;
  if (tiltedMember) {
    tiltedMember.classList.remove("is-tilting");
    tiltedMember.style.removeProperty("--tilt-x");
    tiltedMember.style.removeProperty("--tilt-y");
  }
  tiltedMember = null;
  memberTiltBounds = null;
}

memberRail.addEventListener("pointermove", event => {
  if (event.pointerType === "touch" || !memberTiltPointer.matches || memberReducedMotion.matches) return;
  const card = event.target.closest(".member-card");
  if (!card || card.inert) { resetMemberTilt(); return; }
  if (card !== tiltedMember) {
    resetMemberTilt();
    const railBounds = memberRail.getBoundingClientRect();
    memberTiltBounds = {
      left: railBounds.left + card.offsetLeft,
      top: railBounds.top + card.offsetTop,
      width: card.offsetWidth,
      height: card.offsetHeight
    };
    tiltedMember = card;
    card.classList.add("is-tilting");
  }
  memberPointer = { x: event.clientX, y: event.clientY };
  if (memberTiltFrame) return;
  memberTiltFrame = requestAnimationFrame(() => {
    memberTiltFrame = 0;
    if (!tiltedMember || !memberTiltBounds) return;
    const x = Math.max(-1, Math.min(1, (memberPointer.x - memberTiltBounds.left) / memberTiltBounds.width * 2 - 1));
    const y = Math.max(-1, Math.min(1, (memberPointer.y - memberTiltBounds.top) / memberTiltBounds.height * 2 - 1));
    tiltedMember.style.setProperty("--tilt-x", `${(-y * 5).toFixed(2)}deg`);
    tiltedMember.style.setProperty("--tilt-y", `${(x * 7).toFixed(2)}deg`);
  });
});
memberRail.addEventListener("pointerout", event => {
  if (tiltedMember && !tiltedMember.contains(event.relatedTarget)) resetMemberTilt();
});
memberRail.addEventListener("pointercancel", resetMemberTilt);
memberRail.addEventListener("click", resetMemberTilt);
window.addEventListener("blur", resetMemberTilt);
window.addEventListener("resize", updateCarousel);
// Re-align after responsive layout and font loading change the rail width.
if (typeof ResizeObserver !== "undefined") {
  new ResizeObserver(updateCarousel).observe(memberRail);
}
memberTiltPointer.addEventListener("change", resetMemberTilt);
memberReducedMotion.addEventListener("change", resetMemberTilt);

