// Optional social and business website links share the existing profile section.
// Empty/invalid URLs are hidden; only safe web protocols and escaped URLs render.
function renderMemberSocials(member) {
  const icons = {
    instagram: '<rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r=".8" fill="currentColor" stroke="none"/>',
    linkedin: '<rect x="3" y="9" width="4" height="12" rx=".5"/><circle cx="5" cy="4.5" r="2"/><path d="M11 21V9h4v2c1-3 6-3 6 2v8h-4v-7c0-2-2-2-2 0v7z"/>',
    website: '<circle cx="12" cy="12" r="9"/><ellipse cx="12" cy="12" rx="4" ry="9"/><path d="M3 12h18M5 6h14M5 18h14"/>'
  };
  const labels = { instagram: "Instagram", linkedin: "LinkedIn", website: "Website" };
  const links = ["instagram", "linkedin", "website"].map(platform => {
    const value = member[platform];
    if (typeof value !== "string" || !value.trim()) return "";
    if (!/^https?:\/\//i.test(value.trim()) || /[\u0000-\u001f\u007f]/.test(value)) return "";
    let url;
    try {
      url = new URL(value.trim());
    } catch {
      return "";
    }
    const domain = `${platform}.com`;
    if (url.username || url.password) return "";
    if (platform === "website") {
      if (!["https:", "http:"].includes(url.protocol) || !url.hostname) return "";
    } else if (url.protocol !== "https:" ||
        !(url.hostname === domain || url.hostname.endsWith(`.${domain}`))) return "";
    const href = url.href.replace(/&/g, "&amp;").replace(/"/g, "&quot;")
      .replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const label = labels[platform];
    return `<a class="member-social-link" href="${href}" target="_blank" rel="noopener noreferrer" aria-label="${label} (opens in a new tab)">
      <svg class="member-social-icon" width="18" height="18" viewBox="0 0 24 24" aria-hidden="true" focusable="false" fill="none" stroke="currentColor" stroke-width="1.6">${icons[platform]}</svg>
      <span>${label}</span>
    </a>`;
  }).join("");
  return links ? `<div class="member-socials" role="group" aria-label="Social profiles and business website">${links}</div>` : "";
}

