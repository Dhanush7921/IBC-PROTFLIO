function getNextMeetingDate(
  fromDate = new Date()
) {

  const base =
    new Date(fromDate);


  base.setHours(
    0,
    0,
    0,
    0
  );


  for (
    let offset = 0;
    offset <= 7;
    offset++
  ) {

    const date =
      new Date(base);


    date.setDate(
      base.getDate() + offset
    );


    const day =
      date.getDay();


    // Tuesday = 2
    // Thursday = 4

    if (
      day === 2 ||
      day === 4
    ) {

      return date;

    }

  }


  return base;

}


/* =========================================================
   UPDATE MEETING ALERT
========================================================= */

function updateMeetingSchedule() {

  const today =
    new Date();


  const day =
    today.getDay();


  const isMeetingDay =

    day === 2 ||
    day === 4;


  if (isMeetingDay) {

    nextMeetingDisplay.textContent =
      "TODAY";


    const dayName =

      day === 2
        ? "Tuesday"
        : "Thursday";


    meetingAlertText.textContent =

      `${dayName} meeting is scheduled today.`;


    meetingAlert.classList.add(
      "show"
    );

  }

  else {

    const nextMeetingDate =
      getNextMeetingDate(today);


    const dayText =

      nextMeetingDate
        .toLocaleDateString(
          "en-IN",
          {
            weekday: "short"
          }
        )
        .toUpperCase();


    const dateText =

      String(
        nextMeetingDate.getDate()
      )
        .padStart(
          2,
          "0"
        );


    nextMeetingDisplay.textContent =

      `${dayText} ${dateText}`;

  }

}


