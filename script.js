let page = 0;
// Match the existing CSS breakpoints so all members remain reachable on mobile.
function getMemberPageSize() {
  return window.matchMedia("(max-width: 720px)").matches ? 1 :
    window.matchMedia("(max-width: 1050px)").matches ? 3 : 5;
}

let lastFocusedCard = null;


/* =========================================================
   MEMBER CARDS
========================================================= */

// Neutral default portrait; embedded so missing files never require a new asset.
const DEFAULT_MEMBER_IMAGE = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(
  '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="480" viewBox="0 0 360 480"><circle cx="180" cy="140" r="74" fill="#887469"/><path d="M44 480V366c0-78 61-126 136-126s136 48 136 126v114" fill="#56473f"/><path d="M132 252l48 74 48-74" fill="#a38470"/></svg>'
);

// Quotes are plain text, including when edited later with apostrophes or markup.
function escapeMemberText(value) {
  return String(value ?? "").replace(/[&<>"']/g, character =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]);
}

function renderMemberQuote(member, className) {
  const quote = typeof member.quote === "string" ? member.quote.trim() : "";
  if (!quote) return className === "member-quote" ? '<span class="member-quote" aria-hidden="true"></span>' : "";
  return `<span class="${className}">“${escapeMemberText(quote)}”</span>`;
}

// Try each distinct portrait once, then a self-contained default. Attach before
// setting src so even a cached failure is handled in cards and the profile modal.
function loadMemberImage(image, sources, memberName) {
  const candidates = [...new Set(sources.filter(source => typeof source === "string" && source.trim()))];
  candidates.push(DEFAULT_MEMBER_IMAGE);
  let attempt = 0;
  const showNext = () => {
    if (attempt >= candidates.length) {
      image.hidden = true;
      return;
    }
    const source = candidates[attempt++];
    if (source === DEFAULT_MEMBER_IMAGE) image.alt = `Portrait unavailable for ${memberName}`;
    image.src = source;
  };
  image.addEventListener("error", showNext);
  showNext();
}

